function getHymnInfo(num) {
    const n = parseInt(num, 10);
    if (isNaN(n) || n < 1 || n > 645) return null;
    if (HYMN_POPULAR_LYRICS[n]) {
        return HYMN_POPULAR_LYRICS[n];
    }
    const title = HYMN_TITLES_INDEX[n] || `새찬송가 ${n}장`;
    return {
        num: n,
        title: title,
        engTitle: "Korean Hymnal",
        lyrics: `[새찬송가 ${n}장: ${title}]
은혜로운 찬송가 말씀과 은혜의 멜로디를 찬양합니다.
(아래 '유튜브 찬송 듣기'를 누르시면 은혜로운 피아노 연주와 찬양을 감상하실 수 있습니다.)`
    };
}

window.getHymnInfo = getHymnInfo;
